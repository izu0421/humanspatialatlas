"""Build the manuscript page: the figures the notebook produced, with their legends.

Every figure here is written by lr_atlas/1_2_per_class_prediction.ipynb and copied, never
redrawn. A manuscript figure that is regenerated by the page would be free to drift from the
notebook that computed it, and the first time the two disagreed nobody would know which was
right.

The page is a sibling of index.html on the same GitHub Pages site, so it inherits the same
access controls; the dashboard links to it.
"""
from __future__ import annotations

import base64
import logging
import shutil
from pathlib import Path

import pandas as pd

from .config import RUNS

logger = logging.getLogger(__name__)
ROOT = RUNS.parent
FIGDIR = ROOT.parent / "lr_atlas" / "figures"
OUTFIG = ROOT / "figures"

# (file stem, figure label, title, legend)
FIGURES = [
    ("f1a_framework", "Figure 1a", "An agent per stage",
     "Seven agents, each re-run as new data is deposited. Every stage is labelled with the "
     "number it produced, read from the manifest when the figure is drawn, so the schematic "
     "cannot describe a pipeline different from the one that ran."),
    ("f1b_per_organ", "Figure 1b", "Cells and spots per organ and platform",
     "Measured units by organ and by platform, on a log scale. Cells and spots are shown "
     "side by side and never summed: a Visium spot holds 1-10 cells and a segmented cell is "
     "one cell, so a total of the two is a number that is neither. A Visium HD section that "
     "bin2cell segmented contributes its cells, and its bins are excluded, because they are "
     "the same tissue measured twice."),
    ("f1a_cohort", "Figure 1c", "Cohort composition",
     "Tissues sampled, the interaction classes in the CellPhoneDB universe, and how many "
     "tissues each pair is measurable in. A pair is measurable only where both its genes are "
     "detected, which is why the right-hand panel matters for every figure that follows."),
    ("f2a_ppi_types", "Figure 2a", "Four physical events, one statistic",
     "The interaction classes are not interchangeable. A secreted ligand reaching a receptor, "
     "two adhesion molecules binding across a membrane, a metabolite produced by an enzyme "
     "acting on a receptor, and two receptors engaging directly are different physical events, "
     "and the same bivariate statistic is applied to all four."),
    ("f2_auroc_panels", "Figure 2b-d", "Discrimination, against a shuffled null",
     "AUROC from bootstrap resamples of pairs; hatched grey is the same statistic with the "
     "predictions shuffled. Reported against the shuffled null rather than against 0.5, because "
     "with 2,699 positives concentrated on well-annotated genes, 0.5 is not what a useless "
     "predictor scores on this label set. <b>b</b> aggregation metric, <b>c</b> by interaction "
     "class, <b>d</b> by tissue."),
    ("f4_scaling_per_class", "Figure 3", "How much atlas each class needs",
     "AUROC against atlas size, per interaction class. The pair set is fixed once over the whole "
     "corpus so the curve cannot be confounded by pairs entering as N grows, and sections are "
     "drawn by study rather than individually, since sections from one study share tissue, "
     "protocol and often donor. Metabolite-Receptor gains +0.183 and is the only class still "
     "improving past 100 sections; canonical Ligand-Receptor gains +0.060 and saturates by 32."),
]


def _b64(p: Path) -> str:
    return base64.b64encode(p.read_bytes()).decode()


def build() -> Path:
    OUTFIG.mkdir(parents=True, exist_ok=True)
    try:
        from . import export as _ex
        h = _ex.headline()
    except Exception:
        h = {}

    blocks = []
    for stem, label, title, legend in FIGURES:
        src = FIGDIR / f"{stem}.png"
        if not src.exists():
            logger.warning("missing figure %s", src.name)
            continue
        shutil.copy(src, OUTFIG / src.name)
        svg = FIGDIR / f"{stem}.svg"
        if svg.exists():
            shutil.copy(svg, OUTFIG / svg.name)
        blocks.append(
            f'<figure id="{stem}">\n'
            f'  <img src="data:image/png;base64,{_b64(src)}" alt="{title}">\n'
            f'  <figcaption><b>{label} &mdash; {title}.</b> {legend}</figcaption>\n'
            f'</figure>')

    n_cells = f"{h.get('cells', 0):,}"
    n_spots = f"{h.get('spots', 0):,}"
    n_samp = f"{h.get('samples_loaded', 0):,}"
    n_ds = f"{h.get('datasets', 0):,}"
    n_tis = f"{h.get('tissues', 0):,}"

    html = f"""<!doctype html>
<html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>HSA &mdash; manuscript figures</title>
<style>
 :root {{ --ink:#1a1a1a; --mut:#666; --line:#e4e4e8; --accent:#6a4c93; }}
 * {{ box-sizing:border-box }}
 body {{ margin:0; background:#fff; color:var(--ink);
        font:15px/1.62 -apple-system,BlinkMacSystemFont,"Segoe UI",Helvetica,Arial,sans-serif; }}
 .wrap {{ max-width:1080px; margin:0 auto; padding:34px 22px 80px; }}
 header {{ border-bottom:1px solid var(--line); padding-bottom:18px; margin-bottom:26px; }}
 h1 {{ font-size:25px; margin:0 0 6px; letter-spacing:-.01em; }}
 .sub {{ color:var(--mut); font-size:13.5px; }}
 .stats {{ display:flex; flex-wrap:wrap; gap:26px; margin:18px 0 0; }}
 .stats div b {{ display:block; font-size:19px; color:var(--accent); }}
 .stats div span {{ font-size:11.5px; color:var(--mut); text-transform:uppercase;
                    letter-spacing:.04em; }}
 figure {{ margin:0 0 42px; }}
 figure img {{ width:100%; height:auto; border:1px solid var(--line); border-radius:7px;
               background:#fff; }}
 figcaption {{ font-size:13px; color:#333; margin-top:11px; line-height:1.58; }}
 figcaption b {{ color:var(--ink); }}
 .back {{ display:inline-block; margin-bottom:22px; font-size:13.5px; color:var(--accent);
          text-decoration:none; }}
 .back:hover {{ text-decoration:underline; }}
 .note {{ background:#faf8fc; border-left:3px solid var(--accent); padding:13px 16px;
          font-size:13px; color:#444; margin:0 0 34px; border-radius:0 5px 5px 0; }}
 @media (prefers-color-scheme: dark) {{
   :root {{ --ink:#e8e8ea; --mut:#9a9aa2; --line:#2e2e34; }}
   body {{ background:#141417; }}
   figure img {{ background:#fff; }}
   .note {{ background:#1c1a20; color:#c8c8ce; }}
   figcaption {{ color:#c0c0c6; }}
 }}
</style></head><body><div class="wrap">
<a class="back" href="index.html">&larr; back to the atlas</a>
<header>
  <h1>Ligand&ndash;receptor inference across a cross-tissue spatial atlas</h1>
  <div class="sub">Figures generated by
    <code>lr_atlas/1_2_per_class_prediction.ipynb</code>; this page embeds them unchanged.</div>
  <div class="stats">
    <div><b>{n_cells}</b><span>cells</span></div>
    <div><b>{n_spots}</b><span>spots &amp; bins</span></div>
    <div><b>{n_samp}</b><span>samples</span></div>
    <div><b>{n_ds}</b><span>datasets</span></div>
    <div><b>{n_tis}</b><span>tissues</span></div>
  </div>
</header>
<p class="note"><b>On reading the AUROCs.</b> A pair's degree in CellPhoneDB &mdash; how many
annotated interactions each of its genes already appears in &mdash; predicts the label at
AUROC 0.771, using no expression and no spatial information at all. Every data-derived score
below sits under that, so these numbers should be read against 0.77 from a lookup table rather
than against 0.5. The comparisons are unaffected, since all scores are measured against the same
labels; and for an orphan receptor, where deorphanisation operates, degree carries no information
by construction (AUROC 0.500) while the spatial aggregate is at its best (0.637).</p>
{chr(10).join(blocks)}
</div></body></html>
"""
    # The manuscript carries the same atlas figures and totals as the dashboard, so it gets the
    # same protection. Leaving it in the clear beside an encrypted index.html would publish, in
    # a prettier form, exactly what the password was put there to hold back.
    out = ROOT / "manuscript.html"
    try:
        from .logo import svg
        from .protect import protect
        favicon = "data:image/svg+xml;base64," + base64.b64encode(svg().encode()).decode()
        locked = protect(html, favicon,
                         svg(inline=False).replace("xmlns=", 'class="logo" role="img" '
                                                   'aria-label="HSA logo" xmlns='))
    except Exception as e:
        logger.warning("could not protect the manuscript page: %s", e)
        locked = None
    out.write_text(locked or html)
    logger.info("wrote %s with %d figures (%s)", out, len(blocks),
                "encrypted" if locked else "PLAINTEXT - no password file")
    return out


if __name__ == "__main__":
    logging.basicConfig(level=logging.INFO, format="%(asctime)s %(message)s")
    build()
