def _legend(notebook_stem: str, label: str) -> str:
    """The legend for `label`, taken from the notebook that draws that figure.

    The legend is the markdown cell beginning with the figure's own label, so one
    notebook can carry more than one figure and a legend can never be attached to the
    wrong panels. Returns an empty string when the notebook is missing or carries no
    matching cell, so a page build never fails on a figure whose notebook has not run.
    """
    import json

    nb_path = MANUSCRIPT / f"{notebook_stem}.ipynb"
    if not nb_path.exists():
        logger.warning("no notebook for %s", notebook_stem)
        return ""
    cells = json.loads(nb_path.read_text()).get("cells", [])
    for cell in reversed(cells):
        if cell.get("cell_type") != "markdown":
            continue
        text = "".join(cell.get("source", []))
        if text.lstrip().startswith(f"**{label} "):
            return _markdown_to_html(text)
    logger.warning("no legend for %s in %s", label, nb_path.name)
    return ""


def _markdown_to_html(text: str) -> str:
    """The small subset of markdown the legends use: bold, inline code, paragraphs."""
    import html as _html

    out = _html.escape(text)
    out = re.sub(r"\*\*(.+?)\*\*", r"<b>\1</b>", out, flags=re.S)
    out = re.sub(r"`(.+?)`", r"<code>\1</code>", out)
    paragraphs = [p.replace("\n", " ").strip() for p in out.split("\n\n") if p.strip()]
    return "".join(f"<p>{p}</p>" for p in paragraphs)


def _b64(p: Path) -> str:
    return base64.b64encode(p.read_bytes()).decode()


def build() -> Path:
    OUTFIG.mkdir(parents=True, exist_ok=True)
    try:
        from . import export as _ex
        h = _ex.headline()
    except Exception:
        h = {}

    blocks = []
    for notebook_stem, stem, label, title in FIGURES:
        legend = _legend(notebook_stem, label)
        src = FIGDIR / f"{stem}.png"
        if not src.exists():
            logger.warning("missing figure %s", src.name)
            continue
        shutil.copy(src, OUTFIG / src.name)
        svg = FIGDIR / f"{stem}.svg"
        if svg.exists():
            shutil.copy(svg, OUTFIG / svg.name)
