"""Build the manuscript page: the figures the notebooks produced, with their legends.

Every figure here is written by one notebook in `manuscript/` -- one notebook per figure --
and copied, never redrawn. A manuscript figure that is regenerated by the page would be free
to drift from the notebook that computed it, and the first time the two disagreed nobody
would know which was right.

For the same reason the legend is READ from the notebook rather than restated here: it is the
final markdown cell of the notebook that draws the figure, so a legend cannot describe a panel
that no longer exists.

The page is a sibling of index.html on the same GitHub Pages site, so it inherits the same
access controls; the dashboard links to it.
"""
